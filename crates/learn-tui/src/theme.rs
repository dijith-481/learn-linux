    /// Return the next theme in cycle order, wrapping back to the first.
    pub(crate) fn next(self) -> Self {
        let all = Self::ALL;
        all.iter()
            .position(|candidate| *candidate == self)
            .map_or(all[0], |index| all[(index + 1) % all.len()])
    }

